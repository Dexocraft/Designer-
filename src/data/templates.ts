export function createId(prefix = 'el'): string {
  return `${prefix}_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 7)}`;
}

export function createTextElement(
  fieldType: TextFieldType,
  orientation: CardOrientation,
  overrides: Partial<TextElement> = {}
): TextElement {
  const metrics = getCanvasMetrics(orientation);
  const defaults: Record<
    TextFieldType,
    { text: string; fontSize: number; fontWeight: 400 | 700; width: number; height: number }
  > = {
    name: { text: 'Elena Vance', fontSize: 52, fontWeight: 700, width: 480, height: 74 },
    title: { text: 'Principal Architect', fontSize: 28, fontWeight: 400, width: 420, height: 46 },
    company: { text: 'VANCE & PARTNERS', fontSize: 30, fontWeight: 700, width: 460, height: 50 },
    phone: { text: '+1 (415) 890-4412', fontSize: 24, fontWeight: 400, width: 380, height: 40 },
    email: { text: 'elena@vancepartners.studio', fontSize: 24, fontWeight: 400, width: 460, height: 40 },
    website: { text: 'vancepartners.studio', fontSize: 24, fontWeight: 400, width: 400, height: 40 },
    tagline: { text: 'Spatial design for enduring places.', fontSize: 24, fontWeight: 400, width: 500, height: 44 },
    custom: { text: 'Custom text block', fontSize: 28, fontWeight: 400, width: 380, height: 48 },
  };

  const spec = defaults[fieldType];
  const width = Math.min(overrides.width ?? spec.width, metrics.safeW);
  const height = overrides.height ?? spec.height;

  return {
    id: createId('txt'),
    type: 'text',
    fieldType,
    text: spec.text,
    x: Math.round((metrics.fullW - width) / 2),
    y: Math.round((metrics.fullH - height) / 2),
    width,
    height,
    rotation: 0,
    opacity: 1,
    fontFamily: 'Plus Jakarta Sans',
    fontSize: spec.fontSize,
    fontWeight: spec.fontWeight,
    fontStyle: 'normal',
    textAlign: 'left',
    color: '#0F172A',
    letterSpacing: 0,
    lineHeight: 1.25,
    ...overrides,
  };
}

export function createBlankSide(bgColor = '#FFFFFF'): CardSide {
  return {
    background: {
      type: 'solid',
      color: bgColor,
      gradientStart: '#FFFFFF',
      gradientEnd: '#E2E8F0',
      gradientAngle: 135,
    },
    elements: [],
  };
}

export interface CardTemplate {
  id: string;
  name: string;
  subtitle: string;
  orientation: CardOrientation;
  accentSwatch: string;
  bgSwatch: string;
  build: () => CardProject;
}

export function createStarterProject(): CardProject {
  return CARD_TEMPLATES[0].build();
}

export function createBlankProject(orientation: CardOrientation = 'horizontal'): CardProject {
  return {
    id: createId('proj'),
    name: 'Untitled Business Card',
    updatedAt: new Date().toISOString(),
    sidedness: 'double',
    orientation,
    accepted: false,
    guides: {
      showBleed: true,
      showTrim: true,
      showSafeZone: true,
    },
    front: createBlankSide('#FFFFFF'),
    back: createBlankSide('#0F172A'),
  };
}

