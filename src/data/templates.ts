/**
 * Proportionally remaps and clamps elements when toggling between Horizontal and Vertical orientations
 * so elements remain inside the safe/trim workspace instead of drifting off-canvas.
 */
export function remapSideForOrientation(
  side: CardSide,
  fromOrientation: CardOrientation,
  toOrientation: CardOrientation
): CardSide {
  if (fromOrientation === toOrientation) return side;
  const fromM = getCanvasMetrics(fromOrientation);
  const toM = getCanvasMetrics(toOrientation);

  const elements: CardElement[] = side.elements.map((el) => {
    const centerXRatio = (el.x + el.width / 2) / fromM.fullW;
    const centerYRatio = (el.y + el.height / 2) / fromM.fullH;
    const nextWidth = Math.min(el.width, toM.safeW);
    const nextHeight =
      el.type === 'image' && el.preserveAspect
        ? Math.round((nextWidth / el.width) * el.height)
        : Math.min(el.height, toM.safeH);

    const rawX = Math.round(centerXRatio * toM.fullW - nextWidth / 2);
    const rawY = Math.round(centerYRatio * toM.fullH - nextHeight / 2);

    const clampedX = Math.max(
      toM.safeInsetFromEdgePx,
      Math.min(rawX, toM.fullW - toM.safeInsetFromEdgePx - nextWidth)
    );
    const clampedY = Math.max(
      toM.safeInsetFromEdgePx,
      Math.min(rawY, toM.fullH - toM.safeInsetFromEdgePx - nextHeight)
    );

    return {
      ...el,
      x: clampedX,
      y: clampedY,
      width: nextWidth,
      height: nextHeight,
    };
  });

  return {
    ...side,
    elements,
  };
}

